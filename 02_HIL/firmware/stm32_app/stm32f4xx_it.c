/**
 * @file    stm32f4xx_it.c
 * @brief   REFERENCE interrupt handlers for the ROV HIL target (YS-F4Pro).
 *
 * ---------------------------------------------------------------------------
 *  REFERENCE file -- see the header of main.c for how it is meant to be used.
 *  In practice you let CubeMX generate this file and then apply edits 3.3 and
 *  3.4 from firmware/stm32_app/README.md.  Compare against this file after.
 * ---------------------------------------------------------------------------
 *
 *  Which handler does what:
 *
 *   TIM6_DAC_IRQHandler        one 10 ms control tick   -> HIL_Step10ms()
 *   USART1_IRQHandler          IDLE line = end of a burst of setpoint bytes
 *   DMA2_Stream5_IRQHandler    USART1 RX (circular) -- leave generated
 *   DMA2_Stream7_IRQHandler    USART1 TX -- leave generated
 *
 *  Highest priority is group A (USART1, DMA2 RX).  They may preempt the
 *  control tick so that a byte burst is never lost while HIL_Step10ms() is
 *  running.  DMA2_Stream7 (TX) deliberately shares group B with TIM6 -- see
 *  docs/HIL部署与串口通信说明.md section 10.4.
 */

/* Includes ---------------------------------------------------------- */
#include "main.h"
#include "stm32f4xx_it.h"

#include "hil_port.h"        /* hil_port_tim6_isr / hil_port_rx_poll_idle */

/* External handles -------------------------------------------------- */
extern UART_HandleTypeDef huart1;
extern DMA_HandleTypeDef  hdma_usart1_rx;
extern DMA_HandleTypeDef  hdma_usart1_tx;
extern TIM_HandleTypeDef  htim6;

/* ------------------------------------------------------------------ */
/* Cortex-M4 core exceptions                                           */
/* ------------------------------------------------------------------ */

void NMI_Handler(void)        { while (1) { } }

void HardFault_Handler(void)
{
    /* A breakpoint here right after a reset almost always means the DMA
     * handle mix-up described next to HIL_PORT_INIT_UART in
     * hil_port_stm32f4.c: HAL_DMA_IRQHandler() was handed an uninitialised
     * handle and dereferenced its NULL Instance pointer.                  */
    while (1)
    {
    }
}

void MemManage_Handler(void)  { while (1) { } }
void BusFault_Handler(void)   { while (1) { } }
void UsageFault_Handler(void) { while (1) { } }
void SVC_Handler(void)        { }
void DebugMon_Handler(void)   { }
void PendSV_Handler(void)     { }

/**
 * @brief SysTick — 1 ms HAL time base, drives HAL_GetTick() and HAL_Delay().
 *
 * Not used for anything in the control path: the 10 ms cadence comes from
 * TIM6, which is a real hardware timer and therefore free of the drift a
 * software-counted tick would accumulate.
 */
void SysTick_Handler(void)
{
    HAL_IncTick();
}

/* ------------------------------------------------------------------ */
/* TIM6 -- the 10 ms control tick                                      */
/* ------------------------------------------------------------------ */

void TIM6_DAC_IRQHandler(void)
{
    /* hil_port_tim6_isr() reads TIM6->SR, clears UIF and calls
     * HIL_Step10ms().  It deliberately does NOT go through
     * HAL_TIM_IRQHandler(), so keeping the HAL call here as well would run
     * the HAL state machine on top of the register-level handling.        */
    hil_port_tim6_isr();
}

/* ------------------------------------------------------------------ */
/* USART1 -- IDLE line detection                                       */
/* ------------------------------------------------------------------ */

void USART1_IRQHandler(void)
{
    /* A 104-byte setpoint arrives as one back-to-back burst.  The RX DMA
     * runs in circular mode and only moves a write pointer; the IDLE flag
     * is what tells us "the burst has ended, go and harvest the bytes
     * between the last read position and the current DMA write position".
     *
     * __HAL_UART_CLEAR_IDLEFLAG() internally reads SR then DR, which is
     * what actually clears the flag on this family.                       */
    if (__HAL_UART_GET_FLAG(&huart1, UART_FLAG_IDLE))
    {
        __HAL_UART_CLEAR_IDLEFLAG(&huart1);
        {
            extern volatile uint32_t g_dbg_idle;
            g_dbg_idle++;
        }
        hil_port_rx_poll_idle();
    }

    HAL_UART_IRQHandler(&huart1);
}

/* ------------------------------------------------------------------ */
/* DMA -- generated by CubeMX, keep as-is                              */
/* ------------------------------------------------------------------ */

/**
 * @brief USART1 RX DMA (circular).  Left to the HAL; the bytes themselves are
 *        harvested from USART1_IRQHandler via hil_port_rx_poll_idle().
 */
void DMA2_Stream5_IRQHandler(void)
{
    HAL_DMA_IRQHandler(&hdma_usart1_rx);
}

/**
 * @brief USART1 TX DMA.  The HAL completion callback ends up in
 *        HAL_UART_TxCpltCallback() inside hil_port_stm32f4.c, which advances
 *        the software ring buffer and chain-loads the next chunk.
 */
void DMA2_Stream7_IRQHandler(void)
{
    HAL_DMA_IRQHandler(&hdma_usart1_tx);
}
