/**
 * @file    hil_target.c
 * @brief   On-target HIL run-time.  Board independent: all hardware access
 *          goes through the four hil_port_* hooks (see hil_port.h).
 *
 * Control flow per 10 ms tick:
 *
 *      +---------------- g_hil_sp (written by HIL_OnByte from the RX ISR)
 *      |                          ^
 *      |   SETPOINT frame (104 B) |
 *      |                          |
 *   [UART RX] -> HIL_OnByte -> hil_parser_feed -> g_hil_sp, g_hil_sp_fresh = 1
 *                                                     |
 *   [TIM6 ISR] -> HIL_Step10ms <------------------------+
 *                     |
 *                     +-- if fresh: rov_ctrl_deploy_U.{eta,nu,eta_d,nu_d}
 *                     |              <- g_hil_sp
 *                     |              else: keep previous inputs, raise TIMEOUT
 *                     +-- rov_ctrl_deploy_step()
 *                     +-- read rov_ctrl_deploy_Y.u[6]
 *                     +-- hil_pack_command() -> hil_port_uart_write()
 *                     +-- hil_port_apply_u()   -> PWM / DAC / thruster bus
 *
 * NOTE on nu_d: it is the ANALYTIC reference velocity (d/dt eta_d).  It must be
 *       supplied by the host -- the target must never differentiate eta_d
 *       numerically.  A discrete difference of a stepped reference is amplified
 *       by 1/Ts (200x at 10 ms) and makes the closed loop diverge; this was
 *       reproduced and isolated in out/diag_diff.log (see docs section 10).
 */

#include "hil_target.h"
#include "hil_port.h"
#include "rov_ctrl_deploy.h"   /* generated by Embedded Coder */
#include "stm32f4xx.h"         /* DWT / CoreDebug cycle counter */

#include <string.h>

/* ------------------------------------------------------------------ */
/* Module state                                                        */
/* ------------------------------------------------------------------ */

static hil_parser_t   g_ps;                 /* incremental RX parser      */
static hil_setpoint_t g_sp;                 /* last decoded setpoint      */
static volatile uint8_t  g_sp_fresh;        /* set by RX ISR, cleared here*/
static volatile uint32_t g_sp_tick;         /* tick at which SP arrived   */
static volatile uint16_t g_sp_seen;         /* frames seen (for drop calc)*/

volatile float    g_hil_last_u[HIL_N_U];
volatile uint32_t g_hil_tick_cnt  = 0u;
volatile uint32_t g_hil_tx_cnt    = 0u;
volatile uint32_t g_hil_rx_ok     = 0u;
volatile uint32_t g_dbg_idle      = 0u;   /* IDLE ISR hits */
volatile uint32_t g_dbg_restart   = 0u;   /* rx_restart calls */
volatile uint32_t g_dbg_idle_pos  = 0u;   /* s_rx_pos after last idle poll */
volatile uint32_t g_hil_rx_crc    = 0u;
volatile uint32_t g_hil_rx_frame  = 0u;
volatile uint32_t g_hil_rx_drop   = 0u;

/* DWT->CYCCNT execution-time instrumentation of rov_ctrl_deploy_step()
 * (clock = HCLK = 168 MHz; updated only on ticks that consume a setpoint) */
volatile uint32_t g_dbg_cyc_last  = 0u;
volatile uint32_t g_dbg_cyc_max   = 0u;
volatile uint32_t g_dbg_cyc_sum   = 0u;
volatile uint32_t g_dbg_cyc_n     = 0u;

static uint16_t   g_status        = 0u;
static uint16_t   g_echo_seq      = 0u;

/* ------------------------------------------------------------------ */
/* Init                                                                */
/* ------------------------------------------------------------------ */

void HIL_Init(void)
{
    hil_parser_init(&g_ps);
    memset(&g_sp, 0, sizeof(g_sp));
    memset((void *)g_hil_last_u, 0, sizeof(g_hil_last_u));
    g_sp_fresh = 0u;
    g_sp_tick  = 0u;

    /* generated entry point: allocates state, loads parameter constants */
    rov_ctrl_deploy_initialize();

    /* seed the controller inputs with zeros so the first tick is safe  */
    {
        int i;
        for (i = 0; i < HIL_N_ETA; ++i) {
            rov_ctrl_deploy_U.eta[i]   = (real_T)0.0;
            rov_ctrl_deploy_U.eta_d[i] = (real_T)0.0;
        }
        for (i = 0; i < HIL_N_NU; ++i) {
            rov_ctrl_deploy_U.nu[i]   = (real_T)0.0;
            rov_ctrl_deploy_U.nu_d[i] = (real_T)0.0;
        }
    }

    g_status = HIL_ST_INIT_DONE;
    hil_port_init();

    /* enable DWT cycle counter for execution-time measurement */
    CoreDebug->DEMCR |= CoreDebug_DEMCR_TRCENA_Msk;
    DWT->CYCCNT = 0u;
    DWT->CTRL |= DWT_CTRL_CYCCNTENA_Msk;
}

/* ------------------------------------------------------------------ */
/* UART RX path (byte-wise, ISR context)                               */
/* ------------------------------------------------------------------ */

void HIL_OnByte(uint8_t b)
{
    if (hil_parser_feed(&g_ps, b, &g_sp)) {
        /* A complete, CRC-valid setpoint.  Only the freshest one matters:
         * if the previous one was not consumed yet, it is simply dropped. */
        if (g_sp_fresh != 0u) {
            g_hil_rx_drop++;
        }
        g_sp_seen++;
        g_sp_tick  = g_hil_tick_cnt;
        g_sp_fresh = 1u;
        g_hil_rx_ok++;
    }
    g_hil_rx_crc   = g_ps.crc_err;
    g_hil_rx_frame = g_ps.frame_err;
}

/* ------------------------------------------------------------------ */
/* Control tick (TIM ISR context, exactly 100 Hz)                      */
/* ------------------------------------------------------------------ */

void HIL_Step10ms(void)
{
    hil_command_t cmd;
    int           i;
    int           saturated = 0;
    uint16_t      st;

    g_hil_tick_cnt++;

    hil_port_rx_watchdog();     /* self-heal the RX path if HAL killed it */

    /* --- 0. 事件驱动: 没有新 setpoint 的 tick 不步进、不回复 ----------
     * 控制律与自适应律只在真正消费新 setpoint 时前进一次, 与 PC 端
     * 求解步长严格 1:1.  旧行为 (每 tick 无条件 step) 会带来两个问题:
     *   a) PC 发送率略低于 100Hz 时, 同一 setpoint 被自适应律重复积分;
     *   b) PC 读到的自发帧可能基于几拍之前的旧 setpoint, 环路等效
     *      延迟高达 4-5 拍, 10ms 反步闭环直接翻滚失稳 (实测复现).  */
    if (g_sp_fresh == 0u) {
        st = g_status;
        if ((g_hil_tick_cnt - g_sp_tick) > HIL_SETPOINT_TIMEOUT_MS / 10u) {
            st |= HIL_ST_TIMEOUT;   /* 只置标志, 不发帧不打扰 PC */
        } else {
            st &= (uint16_t)~HIL_ST_TIMEOUT;
        }
        g_status = st;
        return;
    }

    st = g_status;

    /* --- 1. latch the freshest setpoint ---------------------------- */
    if (g_sp_fresh != 0u) {
        g_sp_fresh = 0u;
        g_echo_seq = g_sp.seq;

        for (i = 0; i < HIL_N_ETA; ++i) {
            rov_ctrl_deploy_U.eta[i]   = (real_T)g_sp.eta[i];
            rov_ctrl_deploy_U.eta_d[i] = (real_T)g_sp.eta_d[i];
        }
        for (i = 0; i < HIL_N_NU; ++i) {
            rov_ctrl_deploy_U.nu[i]   = (real_T)g_sp.nu[i];
            rov_ctrl_deploy_U.nu_d[i] = (real_T)g_sp.nu_d[i];   /* 参考速度（解析） */
        }
        st |= HIL_ST_DATA_FRESH;
    } else {
        /* No new setpoint this tick: hold previous inputs so that the
         * plant and the controller stay on the same trajectory, but flag
         * the condition so the PC can log it. */
        st &= (uint16_t)~HIL_ST_DATA_FRESH;
    }

    /* --- 2. staleness watchdog ------------------------------------- */
    if ((g_hil_tick_cnt - g_sp_tick) > HIL_SETPOINT_TIMEOUT_MS / 10u) {
        st |= HIL_ST_TIMEOUT;
    } else {
        st &= (uint16_t)~HIL_ST_TIMEOUT;
    }
    if (g_ps.crc_err != 0u)   { st |= HIL_ST_RX_CRC_ERR; }
    if (g_ps.frame_err != 0u) { st |= HIL_ST_RX_OVERFLOW; }

    /* --- 3. one step of the generated controller -------------------- */
    {
        uint32_t c0 = DWT->CYCCNT;
        rov_ctrl_deploy_step();
        uint32_t c1 = DWT->CYCCNT;
        g_dbg_cyc_last = c1 - c0;
        if (g_dbg_cyc_last > g_dbg_cyc_max) { g_dbg_cyc_max = g_dbg_cyc_last; }
        g_dbg_cyc_sum += g_dbg_cyc_last;
        g_dbg_cyc_n++;
    }

    /* --- 4. collect and clamp the 6 thruster commands --------------- */
    for (i = 0; i < HIL_N_U; ++i) {
        real_T v = rov_ctrl_deploy_Y.u[i];

        if (v > HIL_U_MAX) { v = HIL_U_MAX; saturated = 1; }
        if (v < HIL_U_MIN) { v = HIL_U_MIN; saturated = 1; }

        g_hil_last_u[i] = (float)v;
        cmd.u[i]        = (float)v;
    }
    if (saturated) { st |= HIL_ST_SATURATED; } else { st &= (uint16_t)~HIL_ST_SATURATED; }

    /* --- 5. hand the command to the plant -------------------------- */
    hil_port_apply_u(g_hil_last_u, HIL_N_U);

    /* --- 6. send the command frame back to the PC ------------------- */
    cmd.seq    = g_echo_seq;
    cmd.status = st;
    g_status   = st;              /* remember sticky bits for next tick */

    {
        uint8_t frame[HIL_COMMAND_FRAME];
        int     n = hil_pack_command(&cmd, frame);
        if (hil_port_uart_write(frame, (uint16_t)n) == n) {
            g_hil_tx_cnt++;
        } else {
            st |= HIL_ST_TX_FAIL;
            g_status = st;
        }
    }
}

/* ------------------------------------------------------------------ */

void HIL_GetCommand(hil_command_t *out)
{
    int i;
    if (out == 0) { return; }
    for (i = 0; i < HIL_N_U; ++i) { out->u[i] = g_hil_last_u[i]; }
    out->seq    = g_echo_seq;
    out->status = g_status;
}
